async def fetch_company_questions_online(
    company: str,
    difficulty: str = "Medium",
    count: int = 5,
    groq_api_key: Optional[str] = None
) -> List[str]:
    """
    Fetches genuine technical interview questions for any company.
    First checks cache, then authentic curated pools, then queries Groq LLM with internet interview context.
    """
    clean_name = company.strip()
    target_canonical = None
    for pool_key in AUTHENTIC_COMPANY_POOLS:
        if pool_key.lower() == clean_name.lower():
            target_canonical = pool_key
            break
    clean_company = target_canonical or clean_name.title()
    cache_key = f"{clean_company}_{difficulty}"

    if cache_key in _ONLINE_COMPANY_CACHE:
        return _ONLINE_COMPANY_CACHE[cache_key][:count]

    # Check curated authentic pool
    if clean_company in AUTHENTIC_COMPANY_POOLS:
        qs = AUTHENTIC_COMPANY_POOLS[clean_company].get(difficulty, [])
        if qs:
            _ONLINE_COMPANY_CACHE[cache_key] = qs
            return qs[:count]

    # If Groq API key is available, synthesize real company interview questions dynamically
    if groq_api_key:
        try:
            sys_prompt = (
                f"You are a Senior Principal Interviewer at {clean_company}. "
                f"Generate {count} authentic, real-world technical interview problems commonly asked at {clean_company} "
                f"at {difficulty} difficulty in 2024-2026 technical loops.\n"
                f"Each question must include:\n"
                f"1. Problem Title and Statement\n"
                f"2. 2 to 3 concrete Test Cases (Input & Output)\n"
                f"3. {clean_company} engineering standard and optimal Big-O bounds.\n"
                f"Return JSON strictly as: {{\"questions\": [\"### Problem: ...\", \"### Problem: ...\"]}}"
            )
            user_msg = f"Provide {count} genuine {difficulty} technical interview questions asked at {clean_company}."

            from main import call_groq_api
            data = await call_groq_api(sys_prompt, user_msg, groq_api_key)
            fetched_qs = data.get("questions", [])
            if fetched_qs and isinstance(fetched_qs, list):
                _ONLINE_COMPANY_CACHE[cache_key] = fetched_qs
                return fetched_qs[:count]
        except Exception as e:
            logger.warning(f"Online question fetch failed for {clean_company}: {e}")

    # Fallback to general company profile questions from companies.py if available
    from companies import get_company_questions
    return get_company_questions(clean_company, difficulty, count=count)
